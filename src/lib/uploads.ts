import "server-only";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";

// Private file storage for leave documents (FR-17) and notice attachments
// (FR-46). Files live outside public/ and are only served through routes
// that check permissions. For multi-server production, swap this for object
// storage (S3 etc.).

const ROOT = path.join(process.cwd(), "uploads");

type Kind = { mime: string; ext: string; test: (b: Uint8Array, name: string) => boolean; word?: boolean; slides?: boolean };

const SIGNATURES: Kind[] = [
  { mime: "application/pdf", ext: "pdf", test: (b) => b[0] === 0x25 && b[1] === 0x50 && b[2] === 0x44 && b[3] === 0x46 },
  { mime: "image/png", ext: "png", test: (b) => b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47 },
  { mime: "image/jpeg", ext: "jpg", test: (b) => b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff },
  {
    mime: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    ext: "docx",
    word: true,
    test: (b, name) => b[0] === 0x50 && b[1] === 0x4b && b[2] === 0x03 && b[3] === 0x04 && /\.docx$/i.test(name),
  },
  {
    mime: "application/msword",
    ext: "doc",
    word: true,
    test: (b, name) => b[0] === 0xd0 && b[1] === 0xcf && b[2] === 0x11 && b[3] === 0xe0 && /\.doc$/i.test(name),
  },
  {
    mime: "application/vnd.openxmlformats-officedocument.presentationml.presentation",
    ext: "pptx",
    slides: true,
    test: (b, name) => b[0] === 0x50 && b[1] === 0x4b && b[2] === 0x03 && b[3] === 0x04 && /\.pptx$/i.test(name),
  },
  {
    mime: "application/vnd.ms-powerpoint",
    ext: "ppt",
    slides: true,
    test: (b, name) => b[0] === 0xd0 && b[1] === 0xcf && b[2] === 0x11 && b[3] === 0xe0 && /\.ppt$/i.test(name),
  },
];

export type StoredFile = { path: string; name: string; mime: string; size: number };

/** Saves a PDF/JPEG/PNG (and Word, if allowed) after checking its real type by content. */
export async function saveUpload(file: File, folder: "leave" | "notices" | "notes", maxMb: number, opts: { allowWord?: boolean; allowSlides?: boolean } = {}): Promise<StoredFile> {
  if (file.size > maxMb * 1024 * 1024) throw new Error(`The file is larger than ${maxMb} MB.`);
  const bytes = new Uint8Array(await file.arrayBuffer());
  const kind = SIGNATURES.find((s) => (opts.allowWord || !s.word) && (opts.allowSlides || !s.slides) && s.test(bytes, file.name));
  if (!kind) {
    throw new Error(
      opts.allowSlides ? "Only PDF, Word, PowerPoint, JPEG or PNG files are accepted." : opts.allowWord ? "Only PDF, JPEG, PNG or Word files are accepted." : "Only PDF, JPEG or PNG files are accepted.",
    );
  }
  const relative = `${folder}/${randomUUID()}.${kind.ext}`;
  await mkdir(path.join(ROOT, folder), { recursive: true });
  await writeFile(path.join(ROOT, relative), bytes);
  const name = file.name.replace(/[^\w.\- ]+/g, "_").slice(0, 120) || `document.${kind.ext}`;
  return { path: relative, name, mime: kind.mime, size: file.size };
}

export async function readUpload(relative: string): Promise<Buffer> {
  // Stored paths are generated by saveUpload; refuse anything else.
  if (!/^[a-z]+\/[0-9a-f-]{36}\.(pdf|png|jpg|docx|doc|pptx|ppt)$/.test(relative)) throw new Error("Invalid file path.");
  return readFile(path.join(ROOT, relative));
}

/** Removes a stored file (best effort; a missing file is not an error). */
export async function deleteUpload(relative: string): Promise<void> {
  if (!/^[a-z]+\/[0-9a-f-]{36}\.(pdf|png|jpg|docx|doc|pptx|ppt)$/.test(relative)) return;
  await unlink(path.join(ROOT, relative)).catch(() => undefined);
}
